//! A deliberately small, native macOS overlay host.
//!
//! This crate is the AppKit containment boundary for ArenaNext. It has no
//! browser runtime, webview, game-process integration, screen-capture code,
//! file-system access, or Hearthstone-specific logic. It only owns an
//! `NSPanel` and renders a text model supplied by the caller.
//!
//! All public [`OverlayHost`] methods must run on the macOS main thread. The
//! type is deliberately `!Send` and `!Sync`; a caller with a background parser
//! should marshal model updates onto its main-thread event loop.

