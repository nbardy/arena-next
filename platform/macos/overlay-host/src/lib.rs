    /// Converts ScreenCaptureKit's top-left desktop coordinates to AppKit's
    /// bottom-left global coordinates. Current Hearthstone capture selects the
    /// primary game surface; the containing screen's top edge is used when it
    /// can be identified, with the main screen as a safe fallback.
    pub fn bounds_from_top_left(
        &self,
        x: f64,
        y: f64,
        width: f64,
        height: f64,
    ) -> Result<OverlayBounds, OverlayError> {
        let main_thread = require_main_thread()?;
        let screens = NSScreen::screens(main_thread);
        let center_x = x + width / 2.0;
        let mut screen_top = None;
        for index in 0..screens.count() {
            let frame = screens.objectAtIndex(index).frame();
            if center_x >= frame.origin.x && center_x <= frame.origin.x + frame.size.width {
                screen_top = Some(frame.origin.y + frame.size.height);
                break;
            }
        }
        let top = screen_top
            .or_else(|| NSScreen::mainScreen(main_thread).map(|screen| screen.frame().size.height))
            .unwrap_or(0.0);
        let bounds = OverlayBounds::new(x, top - y - height, width, height);
        bounds.validate()?;
        Ok(bounds)
    }

