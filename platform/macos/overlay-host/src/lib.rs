#[derive(Debug, Default)]
struct ActionTargetIvars {
    command: Cell<u8>,
}

define_class!(
    #[unsafe(super = objc2_foundation::NSObject)]
    #[thread_kind = MainThreadOnly]
    #[ivars = ActionTargetIvars]
    struct ActionTarget;

    unsafe impl NSObjectProtocol for ActionTarget {}

    impl ActionTarget {
        #[unsafe(method(showPopup:))]
        fn show_popup(&self, _sender: Option<&AnyObject>) {
            self.ivars().command.set(4);
        }

        #[unsafe(method(toggleOverlay:))]
        fn toggle_overlay(&self, _sender: Option<&AnyObject>) {
            self.ivars().command.set(1);
        }

        #[unsafe(method(toggleInteraction:))]
        fn toggle_interaction(&self, _sender: Option<&AnyObject>) {
            self.ivars().command.set(2);
        }

        #[unsafe(method(quitArenaNext:))]
        fn quit(&self, _sender: Option<&AnyObject>) {
            self.ivars().command.set(3);
        }

        #[unsafe(method(showFixDeckHelp:))]
        fn show_fix_deck_help(&self, _sender: Option<&AnyObject>) {
            self.ivars().command.set(5);
        }
    }
);

impl ActionTarget {
    fn new(mtm: MainThreadMarker) -> Retained<Self> {
        let this = Self::alloc(mtm).set_ivars(ActionTargetIvars::default());
        unsafe { msg_send![super(this), init] }
    }

    fn take_command(&self) -> Option<OverlayCommand> {
        match self.ivars().command.replace(0) {
            1 => Some(OverlayCommand::ToggleVisibility),
            2 => Some(OverlayCommand::ToggleInteraction),
            3 => Some(OverlayCommand::Quit),
            4 => Some(OverlayCommand::ShowPopup),
            5 => Some(OverlayCommand::FixDeckHelp),
            _ => None,
        }
    }
}

/// Commands generated by the native status menu or action affordance.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
